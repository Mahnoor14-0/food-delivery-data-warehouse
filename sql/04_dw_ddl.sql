-- =====================================================================
-- 04_dw_ddl.sql  -  DATA WAREHOUSE SCHEMA (project_dw)
-- Implements the Phase 1 physical model: 12 dimensions + 4 fact tables.
--   * Surrogate keys: IDENTITY (dims) / smart YYYYMMDD key (dim_date) / hour 0-23 (dim_time_of_day)
--   * Natural keys kept + UNIQUE; SCD Type 2 on dim_customer and dim_restaurant
--   * Special members: -1 = Unknown, 0 = None (promotion) are inserted by the load scripts
--   * Audit columns (BRD "Auditability"): etl_batch_id, etl_load_ts on every table
-- TINYINT is not available in PostgreSQL -> SMALLINT is used.
-- =====================================================================
SET search_path = project_dw;

CREATE TABLE etl_scd_log (
    log_id SERIAL PRIMARY KEY, dim_name VARCHAR(30), snapshot_date DATE,
    versions_expired INT, versions_inserted INT, brand_new_members INT, logged_at TIMESTAMP DEFAULT now());

-- ============================================================== DIMENSIONS
CREATE TABLE dim_date (
    date_key INT PRIMARY KEY, full_date DATE NOT NULL UNIQUE, day_of_week_number SMALLINT NOT NULL, day_name VARCHAR(10) NOT NULL,
    day_of_month SMALLINT NOT NULL, day_of_year SMALLINT NOT NULL, week_of_year SMALLINT NOT NULL, week_start_date DATE NOT NULL,
    month_number SMALLINT NOT NULL, month_name VARCHAR(10) NOT NULL, year_month CHAR(7) NOT NULL, quarter_number SMALLINT NOT NULL,
    quarter_name CHAR(2) NOT NULL, year_number SMALLINT NOT NULL, is_weekend BOOLEAN NOT NULL, is_public_holiday BOOLEAN NOT NULL,
    holiday_name VARCHAR(50), etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_time_of_day (
    hour_key SMALLINT PRIMARY KEY, hour_label VARCHAR(11) NOT NULL, hour_12_label VARCHAR(6) NOT NULL, day_part VARCHAR(20) NOT NULL,
    is_peak_hour BOOLEAN NOT NULL, is_late_night_hour BOOLEAN NOT NULL, etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_customer (
    customer_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, customer_id VARCHAR(20) NOT NULL, customer_name VARCHAR(100) NOT NULL,
    gender VARCHAR(10) NOT NULL, age_band VARCHAR(10) NOT NULL, signup_date DATE NOT NULL, tenure_band VARCHAR(15) NOT NULL,
    acquisition_channel VARCHAR(20) NOT NULL, customer_segment VARCHAR(15) NOT NULL, loyalty_tier VARCHAR(10) NOT NULL,
    is_subscriber BOOLEAN NOT NULL, home_zone VARCHAR(50) NOT NULL, home_city VARCHAR(50) NOT NULL,
    effective_start_date DATE NOT NULL, effective_end_date DATE NOT NULL, is_current BOOLEAN NOT NULL, version_number SMALLINT NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now(), UNIQUE (customer_id, version_number));
CREATE UNIQUE INDEX ux_dim_customer_current ON dim_customer (customer_id) WHERE is_current;
CREATE INDEX ix_dim_customer_nk_dates ON dim_customer (customer_id, effective_start_date, effective_end_date);

CREATE TABLE dim_restaurant (
    restaurant_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, restaurant_id VARCHAR(20) NOT NULL, restaurant_name VARCHAR(100) NOT NULL,
    brand_name VARCHAR(100) NOT NULL, chain_type VARCHAR(15) NOT NULL, primary_cuisine VARCHAR(30) NOT NULL, secondary_cuisine VARCHAR(30) NOT NULL,
    is_cloud_kitchen BOOLEAN NOT NULL, onboarding_date DATE NOT NULL, city VARCHAR(50) NOT NULL, zone_name VARCHAR(50) NOT NULL,
    price_tier VARCHAR(10) NOT NULL, partner_tier VARCHAR(10) NOT NULL, commission_rate_pct NUMERIC(5,2) NOT NULL, contract_status VARCHAR(12) NOT NULL,
    effective_start_date DATE NOT NULL, effective_end_date DATE NOT NULL, is_current BOOLEAN NOT NULL, version_number SMALLINT NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now(), UNIQUE (restaurant_id, version_number));
CREATE UNIQUE INDEX ux_dim_restaurant_current ON dim_restaurant (restaurant_id) WHERE is_current;
CREATE INDEX ix_dim_restaurant_nk_dates ON dim_restaurant (restaurant_id, effective_start_date, effective_end_date);

CREATE TABLE dim_menu_item (
    menu_item_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, menu_item_id VARCHAR(20) NOT NULL UNIQUE, item_name VARCHAR(120) NOT NULL,
    item_category VARCHAR(20) NOT NULL, cuisine_type VARCHAR(30) NOT NULL, dietary_type VARCHAR(10) NOT NULL, spice_level VARCHAR(10) NOT NULL,
    is_combo_meal BOOLEAN NOT NULL, list_price NUMERIC(10,2) NOT NULL, owner_restaurant_id VARCHAR(20) NOT NULL, is_active BOOLEAN NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_courier (
    courier_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, courier_id VARCHAR(20) NOT NULL UNIQUE, courier_name VARCHAR(100) NOT NULL,
    vehicle_type VARCHAR(15) NOT NULL, employment_type VARCHAR(12) NOT NULL, hire_date DATE NOT NULL, experience_band VARCHAR(12) NOT NULL,
    base_city VARCHAR(50) NOT NULL, courier_status VARCHAR(10) NOT NULL, etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_location (
    location_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, zone_id VARCHAR(10) NOT NULL UNIQUE, zone_name VARCHAR(50) NOT NULL,
    zone_type VARCHAR(15) NOT NULL, service_tier VARCHAR(10) NOT NULL, city VARCHAR(50) NOT NULL, region VARCHAR(50) NOT NULL,
    country VARCHAR(50) NOT NULL, centroid_latitude NUMERIC(9,6), centroid_longitude NUMERIC(9,6), etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_order_channel (
    channel_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, channel_code VARCHAR(10) NOT NULL UNIQUE, channel_name VARCHAR(30) NOT NULL,
    platform_type VARCHAR(15) NOT NULL, is_self_service BOOLEAN NOT NULL, etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_payment_method (
    payment_method_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payment_method_code VARCHAR(10) NOT NULL UNIQUE,
    payment_method_name VARCHAR(30) NOT NULL, payment_type VARCHAR(15) NOT NULL, is_prepaid BOOLEAN NOT NULL, is_online_payment BOOLEAN NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_order_status (
    order_status_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, order_status_code VARCHAR(15) NOT NULL UNIQUE,
    order_status_name VARCHAR(30) NOT NULL, status_group VARCHAR(12) NOT NULL, is_final_status BOOLEAN NOT NULL, counts_as_revenue BOOLEAN NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_cancellation_reason (
    cancellation_reason_key SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reason_code VARCHAR(15) NOT NULL UNIQUE, reason_name VARCHAR(50) NOT NULL,
    reason_category VARCHAR(15) NOT NULL, cancelled_by VARCHAR(12) NOT NULL, is_preventable BOOLEAN NOT NULL, etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

CREATE TABLE dim_promotion (
    promotion_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, promotion_id VARCHAR(20) NOT NULL UNIQUE, promotion_code VARCHAR(20) NOT NULL,
    promotion_name VARCHAR(100) NOT NULL, campaign_name VARCHAR(100) NOT NULL, promotion_type VARCHAR(20) NOT NULL, discount_value NUMERIC(10,2) NOT NULL,
    discount_unit VARCHAR(8) NOT NULL, funded_by VARCHAR(12) NOT NULL, target_segment VARCHAR(15) NOT NULL, min_order_amount NUMERIC(10,2) NOT NULL,
    start_date DATE NOT NULL, end_date DATE NOT NULL, is_active BOOLEAN NOT NULL, etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());

-- ============================================================== FACTS
CREATE TABLE fact_order_item (
    order_id VARCHAR(20) NOT NULL, order_line_number SMALLINT NOT NULL,
    order_date_key INT NOT NULL REFERENCES dim_date, order_hour_key SMALLINT NOT NULL REFERENCES dim_time_of_day,
    customer_key INT NOT NULL REFERENCES dim_customer, restaurant_key INT NOT NULL REFERENCES dim_restaurant,
    menu_item_key INT NOT NULL REFERENCES dim_menu_item, delivery_location_key INT NOT NULL REFERENCES dim_location,
    channel_key SMALLINT NOT NULL REFERENCES dim_order_channel, payment_method_key SMALLINT NOT NULL REFERENCES dim_payment_method,
    order_status_key SMALLINT NOT NULL REFERENCES dim_order_status, promotion_key INT NOT NULL REFERENCES dim_promotion,
    quantity INT NOT NULL, unit_price NUMERIC(10,2) NOT NULL, gross_item_amount NUMERIC(12,2) NOT NULL, item_discount_amount NUMERIC(12,2) NOT NULL,
    net_item_amount NUMERIC(12,2) NOT NULL, platform_commission_amount NUMERIC(12,2) NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now(), PRIMARY KEY (order_id, order_line_number));
CREATE INDEX ix_foi_date ON fact_order_item (order_date_key);
CREATE INDEX ix_foi_cust ON fact_order_item (customer_key);
CREATE INDEX ix_foi_rest ON fact_order_item (restaurant_key);
CREATE INDEX ix_foi_item ON fact_order_item (menu_item_key);
CREATE INDEX ix_foi_promo ON fact_order_item (promotion_key);

CREATE TABLE fact_delivery (
    delivery_key BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY, order_id VARCHAR(20) NOT NULL UNIQUE,
    customer_key INT NOT NULL REFERENCES dim_customer, restaurant_key INT NOT NULL REFERENCES dim_restaurant, courier_key INT NOT NULL REFERENCES dim_courier,
    pickup_location_key INT NOT NULL REFERENCES dim_location, dropoff_location_key INT NOT NULL REFERENCES dim_location,
    channel_key SMALLINT NOT NULL REFERENCES dim_order_channel, payment_method_key SMALLINT NOT NULL REFERENCES dim_payment_method,
    order_status_key SMALLINT NOT NULL REFERENCES dim_order_status, cancellation_reason_key SMALLINT NOT NULL REFERENCES dim_cancellation_reason,
    promotion_key INT NOT NULL REFERENCES dim_promotion,
    order_placed_date_key INT NOT NULL REFERENCES dim_date, restaurant_accepted_date_key INT NOT NULL REFERENCES dim_date,
    food_ready_date_key INT NOT NULL REFERENCES dim_date, courier_picked_up_date_key INT NOT NULL REFERENCES dim_date,
    order_closed_date_key INT NOT NULL REFERENCES dim_date,
    order_placed_hour_key SMALLINT NOT NULL REFERENCES dim_time_of_day, order_closed_hour_key SMALLINT NOT NULL REFERENCES dim_time_of_day,
    order_placed_ts TIMESTAMP NOT NULL, restaurant_accepted_ts TIMESTAMP, food_ready_ts TIMESTAMP, courier_picked_up_ts TIMESTAMP, order_closed_ts TIMESTAMP,
    items_count SMALLINT, order_subtotal_amount NUMERIC(12,2), order_discount_amount NUMERIC(12,2), delivery_fee_amount NUMERIC(12,2),
    tip_amount NUMERIC(12,2), refund_amount NUMERIC(12,2), order_total_amount NUMERIC(12,2), delivery_distance_km NUMERIC(6,2),
    promised_delivery_minutes SMALLINT, acceptance_lag_minutes NUMERIC(6,2), prep_lag_minutes NUMERIC(6,2), pickup_wait_lag_minutes NUMERIC(6,2),
    transit_lag_minutes NUMERIC(6,2), total_delivery_minutes NUMERIC(6,2), delay_minutes NUMERIC(6,2), delivered_on_time_flag SMALLINT,
    cancelled_flag SMALLINT, customer_rating SMALLINT, etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now());
CREATE INDEX ix_fd_rest ON fact_delivery (restaurant_key);
CREATE INDEX ix_fd_date ON fact_delivery (order_placed_date_key);
CREATE INDEX ix_fd_cour ON fact_delivery (courier_key);
CREATE INDEX ix_fd_drop ON fact_delivery (dropoff_location_key);

CREATE TABLE fact_restaurant_daily_snapshot (
    snapshot_date_key INT NOT NULL REFERENCES dim_date, restaurant_key INT NOT NULL REFERENCES dim_restaurant,
    scheduled_open_minutes SMALLINT, online_minutes SMALLINT, orders_received_count INT, orders_delivered_count INT, orders_cancelled_count INT,
    gross_sales_amount NUMERIC(12,2), avg_food_prep_minutes NUMERIC(6,2), active_menu_items_count SMALLINT, unavailable_menu_items_count SMALLINT,
    avg_rating_to_date NUMERIC(3,2), review_count_to_date INT, open_complaints_count SMALLINT,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now(), PRIMARY KEY (snapshot_date_key, restaurant_key));

CREATE TABLE fact_promotion_eligibility (
    promotion_key INT NOT NULL REFERENCES dim_promotion, customer_key INT NOT NULL REFERENCES dim_customer,
    issue_date_key INT NOT NULL REFERENCES dim_date, expiry_date_key INT NOT NULL REFERENCES dim_date, eligibility_count SMALLINT NOT NULL,
    etl_batch_id INT, etl_load_ts TIMESTAMP DEFAULT now(), PRIMARY KEY (promotion_key, customer_key, issue_date_key));

CREATE TABLE dq_result (
    check_id SERIAL PRIMARY KEY, category VARCHAR(30) NOT NULL, check_name TEXT NOT NULL, table_name VARCHAR(60),
    rows_checked BIGINT, rows_failed BIGINT, tolerance NUMERIC,          -- NULL tolerance = informational metric
    status VARCHAR(4) GENERATED ALWAYS AS (CASE WHEN tolerance IS NULL THEN 'INFO' WHEN rows_failed <= tolerance THEN 'PASS' ELSE 'FAIL' END) STORED,
    run_ts TIMESTAMP DEFAULT now());
